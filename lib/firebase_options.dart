/// Firebase configuration for QuantumLab.
///
/// To configure Firebase for your project:
/// 1. Create a project at https://console.firebase.google.com
/// 2. Run: flutterfire configure
/// 3. Replace the placeholder values below with your actual config
///
/// Until configured, the app runs in offline mode (FirebaseService
/// gracefully handles the unconfigured state).
class DefaultFirebaseOptions {
  static FirebaseOptions get currentPlatform {
    if (kIsWeb) {
      return web;
    }
    switch (defaultTargetPlatform) {
      case TargetPlatform.android:
        return android;
      case TargetPlatform.iOS:
        return ios;
      default:
        throw UnsupportedError('Unsupported platform: $defaultTargetPlatform');
    }
  }

  static const FirebaseOptions web = FirebaseOptions(
    apiKey: 'YOUR_WEB_API_KEY',
    appId: 'YOUR_WEB_APP_ID',
    messagingSenderId: 'YOUR_MESSAGING_SENDER_ID',
